#!/usr/bin/env python3
"""Add the reviewed SOW register seams to ignored compiler copies only."""
from __future__ import annotations

import argparse
from pathlib import Path
import re


def once(text: str, old: str, new: str) -> str:
    count = text.count(old)
    if count != 1:
        raise ValueError(f"Expected exactly one Module 025 source anchor; found {count}: {old[:90]}")
    return text.replace(old, new, 1)


def transform_module(source: str) -> str:
    source = once(source, "public static class Module025SowGsdModule", "public static partial class Module025SowGsdModule")
    for artifact in ("Sow", "Gsd"):
        source = once(source,
            f"private static async Task<IResult> Download{artifact}Async(",
            f"private static async Task<IResult> DownloadLegacy{artifact}Async(")
    start = source.index("    private static async Task<IResult> ConfirmAsync(")
    end = source.index("    private static async Task<IResult> ReopenAsync(", start)
    confirm = source[start:end]
    confirm = once(confirm, "        await using var connection = writable.Connection!;",
        "        await using var connection = writable.Connection!;\n"
        "        if (!await SowSellSchemaReadyAsync(connection, cancellationToken)) return SowSellMigrationRequired();")
    anchor = '        await InsertEventAsync(connection, transaction, engagementId, access.ActualUserId, revision.Value, "confirmed", "Solution Architect confirmed the SOW/GSD package for document export.", new { }, cancellationToken);'
    confirm = once(confirm, anchor, anchor + "\n        await CaptureConfirmedSowVersionAsync(connection, transaction, engagementId, access.ActualUserId, cancellationToken);")
    source = source[:start] + confirm + source[end:]
    return "// Generated by build/generate-module025-sow-sell.py; edit canonical sources.\n#nullable enable\n" + source


def insert_before_line(source: str, anchor: str, addition: str) -> str:
    existing = re.findall(r"^\s*" + re.escape(addition) + r"\s*$", source, re.MULTILINE)
    if len(existing) == 1:
        return source
    if existing:
        raise ValueError(f"Duplicate registration: {addition}")
    expression = re.compile(r"^(?P<indent>[ \t]*)" + re.escape(anchor) + r"[ \t]*$", re.MULTILINE)
    if len(expression.findall(source)) != 1:
        raise ValueError(f"Missing or ambiguous generated Program anchor: {anchor}")
    return expression.sub(lambda match: match.group("indent") + addition + "\n" + match.group(0), source)


def transform_program(source: str) -> str:
    source = insert_before_line(source, "var app = builder.Build();", "builder.Services.AddModule025SowSell();")
    return insert_before_line(source, "app.Run();", "app.MapModule025SowSellEndpoints();")


def write_ignored(path: Path, content: str) -> None:
    if "obj" not in path.resolve().parts:
        raise ValueError("Generated SOW register files must remain inside ignored obj/ directories")
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(content, encoding="utf-8")
    temporary.replace(path)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--program", type=Path, required=True)
    args = parser.parse_args()
    if args.source.resolve() == args.output.resolve():
        parser.error("Canonical Module 025 source must not be overwritten")
    module = transform_module(args.source.read_text(encoding="utf-8"))
    program = transform_program(args.program.read_text(encoding="utf-8"))
    write_ignored(args.output, module)
    write_ignored(args.program, program)


if __name__ == "__main__":
    main()
